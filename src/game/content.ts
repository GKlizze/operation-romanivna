/** Жартівливий коментар до поточного розподілу годин або null, якщо нічого особливого. */
export function hoursSecret(hours: HoursMap): string | null {
  const values = Object.values(hours)
  const total = values.reduce((a, b) => a + b, 0)
  if (total === 0) return null
  if (values.some((v) => v === 10)) return 'Усі десять годин на одне. Це вже не план, це заява.'
  if (hours.hugs >= 6) return 'Шість і більше годин обіймів. Я не проти. Я взагалі не проти.'
  if (hours.adventures >= 5) return 'Хтось хоче пригод. Паспорт брати?'
  if (hours.food >= 5) return 'Їжа — половина дня. Шеф-кухар нервує, але щасливий.'
  if (hours.movies >= 5) return 'П’ять годин фільмів і розмов. Фільми, чесно кажучи, під питанням.'
  if (hours.walks >= 5) return 'Багато прогулянок. Зручне взуття — твоє, рука — моя.'
  if (total === 10 && values.every((v) => v >= 1)) return 'Збалансовано. Стратег. Мені подобається.'
  if (total === 10 && hours.hugs === 0) return 'Нуль годин на обійми? Переглянь, будь ласка. Я почекаю.'
  return null
}
